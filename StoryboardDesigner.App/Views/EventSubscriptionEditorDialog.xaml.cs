    private void SubscriptionNameTextBox_OnTextChanged(object sender, System.Windows.Controls.TextChangedEventArgs e)
    {
        if (_isInitializing || _suppressSubscriptionNameTracking)
        {
            return;
        }

        var current = SubscriptionNameTextBox.Text?.Trim() ?? string.Empty;
        _isAutoGeneratedSubscriptionName = !string.IsNullOrWhiteSpace(_lastAutoGeneratedSubscriptionName)
            && string.Equals(current, _lastAutoGeneratedSubscriptionName, StringComparison.OrdinalIgnoreCase);
    }

    private void TryAutoPopulateSubscriptionNameFromEventKey()
    {
        if (_isInitializing)
        {
            return;
        }

        var selectedEventKey = EventKeyComboBox.Text?.Trim() ?? string.Empty;
        if (string.IsNullOrWhiteSpace(selectedEventKey))
        {
            return;
        }

        var currentName = SubscriptionNameTextBox.Text?.Trim() ?? string.Empty;
        if (!string.IsNullOrWhiteSpace(currentName) && !_isAutoGeneratedSubscriptionName)
        {
            return;
        }

        if (string.Equals(currentName, selectedEventKey, StringComparison.OrdinalIgnoreCase))
        {
            _isAutoGeneratedSubscriptionName = true;
            _lastAutoGeneratedSubscriptionName = selectedEventKey;
            return;
        }

        _suppressSubscriptionNameTracking = true;
        try
        {
            SubscriptionNameTextBox.Text = selectedEventKey;
        }
        finally
        {
            _suppressSubscriptionNameTracking = false;
        }

        _isAutoGeneratedSubscriptionName = true;
        _lastAutoGeneratedSubscriptionName = selectedEventKey;
    }

