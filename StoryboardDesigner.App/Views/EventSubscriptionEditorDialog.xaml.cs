            InputArgumentMappings = new List<EventInputArgumentMappingDefinition>()
        };

        _entry.ActionBindings.Add(binding);
        BindingsDataGrid.ItemsSource = null;
        BindingsDataGrid.ItemsSource = _entry.ActionBindings;
        BindingsDataGrid.SelectedItem = binding;
        BindingsDataGrid.ScrollIntoView(binding);
    }

