    private static IReadOnlyList<KeyValuePair<string, string>> LoadEventPayloadMappingsForEventKey(string eventKey)
    {
        var normalizedEventKey = eventKey?.Trim() ?? string.Empty;
        if (string.IsNullOrWhiteSpace(normalizedEventKey))
        {
            return Array.Empty<KeyValuePair<string, string>>();
        }

        var manifestPath = Path.Combine(AppContext.BaseDirectory, EventPayloadManifestRelativePath);
        if (!File.Exists(manifestPath))
        {
            return Array.Empty<KeyValuePair<string, string>>();
        }

        try
        {
            using var stream = File.OpenRead(manifestPath);
            using var document = JsonDocument.Parse(stream);
            if (!document.RootElement.TryGetProperty("events", out var eventsElement)
                || eventsElement.ValueKind != JsonValueKind.Array)
            {
                return Array.Empty<KeyValuePair<string, string>>();
            }

            var mappings = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (var eventElement in eventsElement.EnumerateArray())
            {
                if (!eventElement.TryGetProperty("eventKey", out var eventKeyElement)
                    || eventKeyElement.ValueKind != JsonValueKind.String)
                {
                    continue;
                }

                var manifestEventKey = eventKeyElement.GetString()?.Trim() ?? string.Empty;
                if (!string.Equals(manifestEventKey, normalizedEventKey, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                if (!eventElement.TryGetProperty("payloadMappings", out var mappingsElement)
                    || mappingsElement.ValueKind != JsonValueKind.Array)
                {
                    continue;
                }

                foreach (var mappingElement in mappingsElement.EnumerateArray())
                {
                    if (!mappingElement.TryGetProperty("payloadKey", out var payloadKeyElement)
                        || payloadKeyElement.ValueKind != JsonValueKind.String)
                    {
                        continue;
                    }

                    if (!mappingElement.TryGetProperty("sourcePath", out var sourcePathElement)
                        || sourcePathElement.ValueKind != JsonValueKind.String)
                    {
                        continue;
                    }

                    var payloadKey = payloadKeyElement.GetString()?.Trim() ?? string.Empty;
                    var sourcePath = sourcePathElement.GetString()?.Trim() ?? string.Empty;
                    if (!string.IsNullOrWhiteSpace(payloadKey)
                        && !string.IsNullOrWhiteSpace(sourcePath)
                        && !mappings.ContainsKey(payloadKey))
                    {
                        mappings[payloadKey] = sourcePath;
                    }
                }
            }

            return mappings
                .OrderBy(static pair => pair.Key, StringComparer.OrdinalIgnoreCase)
                .Select(static pair => new KeyValuePair<string, string>(pair.Key, pair.Value))
                .ToList();
        }
        catch
        {
            return Array.Empty<KeyValuePair<string, string>>();
        }
    }

    private static IReadOnlyList<EventBindingVariableAssistDialog.AnchorSubPropertyDefinition> LoadAnchorSubPropertiesFromManifest()
    {
        try
        {
            var output = new List<EventBindingVariableAssistDialog.AnchorSubPropertyDefinition>();
            foreach (var anchor in new RuntimeSessionAnchorManifestReader().Load().Anchors)
            {
                var anchorKey = anchor.AnchorKey?.Trim() ?? string.Empty;
                if (string.IsNullOrWhiteSpace(anchorKey))
                {
                    continue;
                }

                foreach (var subProperty in anchor.SupportedSubProperties)
                {
                    var propertyKey = subProperty.PropertyKey?.Trim() ?? string.Empty;
                    if (string.IsNullOrWhiteSpace(propertyKey))
                    {
                        continue;
                    }

                    var sourcePath = subProperty.SourcePath?.Trim() ?? string.Empty;
                    var expectedScopeType = string.IsNullOrWhiteSpace(subProperty.ExpectedScopeType)
                        ? "Unknown"
                        : subProperty.ExpectedScopeType.Trim();

                    output.Add(new EventBindingVariableAssistDialog.AnchorSubPropertyDefinition(
                        anchorKey,
                        propertyKey,
                        sourcePath,
                        expectedScopeType));
                }
            }

            return output;
        }
        catch
        {
            return Array.Empty<EventBindingVariableAssistDialog.AnchorSubPropertyDefinition>();
        }
    }

    private IReadOnlyList<EventBindingVariableAssistDialog.ActionOutputVariableDefinition> LoadActionOutputVariablesForBindingAction(
        EventActionBindingDefinition binding)
    {
        var actionName = binding.Target?.ActionName?.Trim() ?? string.Empty;
        if (string.IsNullOrWhiteSpace(actionName)
            || !_actionNameToTypes.TryGetValue(actionName, out var actionTypes)
            || actionTypes.Count == 0)
        {
            return Array.Empty<EventBindingVariableAssistDialog.ActionOutputVariableDefinition>();
        }

        return LoadActionOutputVariableCatalogFromManifest(actionTypes);
    }

    private static IReadOnlyList<EventBindingVariableAssistDialog.ActionOutputVariableDefinition> LoadActionOutputVariableCatalogFromManifest(
        IReadOnlyList<CommandActionType> actionTypes)
    {
        var actionTypeNames = actionTypes
            .Select(static actionType => actionType.ToString())
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        if (actionTypeNames.Count == 0)
        {
            return Array.Empty<EventBindingVariableAssistDialog.ActionOutputVariableDefinition>();
        }

        var manifestPath = Path.Combine(AppContext.BaseDirectory, ActionPayloadManifestRelativePath);
        if (!File.Exists(manifestPath))
        {
            return Array.Empty<EventBindingVariableAssistDialog.ActionOutputVariableDefinition>();
        }

        try
        {
            using var stream = File.OpenRead(manifestPath);
            using var document = JsonDocument.Parse(stream);

            if (!document.RootElement.TryGetProperty("perActionTypeCatalog", out var perActionCatalog)
                || perActionCatalog.ValueKind != JsonValueKind.Array)
            {
                return Array.Empty<EventBindingVariableAssistDialog.ActionOutputVariableDefinition>();
            }

            var results = new List<EventBindingVariableAssistDialog.ActionOutputVariableDefinition>();

            foreach (var actionCatalog in perActionCatalog.EnumerateArray())
            {
                if (!actionCatalog.TryGetProperty("actionType", out var actionTypeElement)
                    || actionTypeElement.ValueKind != JsonValueKind.String)
                {
                    continue;
                }

                var actionTypeText = actionTypeElement.GetString()?.Trim() ?? string.Empty;
                if (!actionTypeNames.Contains(actionTypeText)
                    || !Enum.TryParse<CommandActionType>(actionTypeText, ignoreCase: true, out var actionType))
                {
                    continue;
                }

                if (!actionCatalog.TryGetProperty("actionOutputVariableCatalog", out var outputCatalog)
                    || outputCatalog.ValueKind != JsonValueKind.Array)
                {
                    continue;
                }

                foreach (var outputEntry in outputCatalog.EnumerateArray())
                {
                    var key = ReadTrimmedString(outputEntry, "actionOutputVariableKey");
                    if (string.IsNullOrWhiteSpace(key))
                    {
                        continue;
                    }

                    results.Add(new EventBindingVariableAssistDialog.ActionOutputVariableDefinition(
                        actionType,
                        key,
                        ReadTrimmedString(outputEntry, "description"),
                        ReadTrimmedString(outputEntry, "valueType"),
                        ReadTrimmedString(outputEntry, "notes")));
                }
            }

            return results
                .GroupBy(static item => $"{item.ActionType}|{item.ActionOutputVariableKey}", StringComparer.OrdinalIgnoreCase)
                .Select(static group => group.First())
                .OrderBy(static item => item.ActionType.ToString(), StringComparer.OrdinalIgnoreCase)
                .ThenBy(static item => item.ActionOutputVariableKey, StringComparer.OrdinalIgnoreCase)
                .ToList();
        }
        catch
        {
            return Array.Empty<EventBindingVariableAssistDialog.ActionOutputVariableDefinition>();
        }
    }

    private void Save_OnClick(object sender, RoutedEventArgs e)
    {
        _entry.EventKey = (EventKeyComboBox.SelectedItem as string)?.Trim() ?? string.Empty;
        _entry.SubscriptionName = ResolveSubscriptionDisplayName(
            SubscriptionNameTextBox.Text?.Trim() ?? string.Empty,
            _entry.EventKey);
        _entry.Lane = NormalizeLane(LaneComboBox.SelectedItem as string);
        _entry.IsEnabled = IsEnabledCheckBox.IsChecked == true;
        _entry.SubscriptionVisibleWhenContained = VisibleWhenContainedCheckBox.IsChecked == true;
        _entry.DispatchDisposition = DispatchComboBox.SelectedItem is EventSubscriberDispatchDisposition dispatch
            ? dispatch
            : EventSubscriberDispatchDisposition.bubble;
        _entry.SubscriptionSourceMatchMode = SourceMatchModeComboBox.SelectedItem is SubscriptionSourceMatchMode sourceMatchMode
            ? sourceMatchMode
            : SubscriptionSourceMatchMode.AnySource;

        _entry.SubscriptionSecondarySourceMatchMode = SecondarySourceMatchModeComboBox.SelectedItem is SubscriptionSourceMatchMode secondarySourceMatchMode
            ? secondarySourceMatchMode
            : SubscriptionSourceMatchMode.AnySource;

        var sourceScopeIdText = SourceScopeIdTextBox.Text?.Trim() ?? string.Empty;
        if (string.IsNullOrWhiteSpace(sourceScopeIdText))
        {
            _entry.SubscriptionSourceScopeNodeId = null;
        }
        else if (Guid.TryParse(sourceScopeIdText, out var sourceScopeId) && sourceScopeId != Guid.Empty)
        {
            _entry.SubscriptionSourceScopeNodeId = sourceScopeId;
        }
        else
        {
            WpfMessageBox.Show(
                this,
                "Source Scope Id must be a valid non-empty GUID when provided.",
                "Event Subscription",
                WpfMessageBoxButton.OK,
                WpfMessageBoxImage.Information);
            return;
        }

        var secondarySourceScopeIdText = SecondarySourceScopeIdTextBox.Text?.Trim() ?? string.Empty;
        if (string.IsNullOrWhiteSpace(secondarySourceScopeIdText))
        {
            _entry.SubscriptionSecondarySourceScopeNodeId = null;
        }
        else if (Guid.TryParse(secondarySourceScopeIdText, out var secondarySourceScopeId) && secondarySourceScopeId != Guid.Empty)
        {
            _entry.SubscriptionSecondarySourceScopeNodeId = secondarySourceScopeId;
        }
        else
        {
            WpfMessageBox.Show(
                this,
                "Secondary Source Scope Id must be a valid non-empty GUID when provided.",
                "Event Subscription",
                WpfMessageBoxButton.OK,
                WpfMessageBoxImage.Information);
            return;
        }

        if (_entry.Id == Guid.Empty)
        {
            _entry.Id = Guid.NewGuid();
        }

        var errors = ValidateEntry(_entry);
        if (errors.Count > 0)
        {
            WpfMessageBox.Show(
                this,
                string.Join(Environment.NewLine, errors),
                "Event Subscription",
                WpfMessageBoxButton.OK,
                WpfMessageBoxImage.Information);
            return;
        }

        Entry = CloneEntry(_entry);
        DialogResult = true;
    }

