    private void AddBinding_OnClick(object sender, RoutedEventArgs e)
    {
        var nextOrder = _entry.ActionBindings.Count == 0
            ? 1
            : _entry.ActionBindings.Max(static binding => binding.Order) + 1;
        var binding = new EventActionBindingDefinition
        {
            Order = nextOrder,
            IsEnabled = true,
            Condition = new EventBindingConditionDefinition
            {
                QuantityEvaluationMode = RuntimeVariableQuantityEvaluationMode.AllResolvedMustPass
            },
            Target = new EventBindingTargetDefinition
            {
                ActionName = _actionNameSuggestions.FirstOrDefault() ?? "inspect",
                OnMissingAction = DefaultOnMissingAction,
                StopChainOnFailure = true
