    {
        InitializeComponent();
        _isInitializing = true;

        _entry = CloneEntry(initialEntry);
        _entry.ActionBindings ??= new List<EventActionBindingDefinition>();
        _entry.InputArgumentMappings ??= new List<EventInputArgumentMappingDefinition>();
        var initialEventKey = _entry.EventKey?.Trim() ?? string.Empty;
        EventKeyOptions = NormalizeSuggestions([
            ..(eventKeyOptions ?? Array.Empty<string>()),
            initialEventKey
        ]);
        _actionNameSuggestions = NormalizeSuggestions(actionNameSuggestions);
        _filterVariableSuggestions = NormalizeSuggestions(filterVariableSuggestions);
        _anchorOptions = NormalizeSuggestions(anchorOptions);
        _filterVariableChoices = (filterVariableChoices ?? Array.Empty<GamePropertyChoiceItem>())
            .Where(static choice => !string.IsNullOrWhiteSpace(choice.Value))
            .ToList();
        _sourceScopeChoices = NormalizeSourceScopeChoices(sourceScopeChoices);
        _soundEffectKeySuggestions = NormalizeSuggestions(soundEffectKeySuggestions);
        _actionNameToTypes = NormalizeActionTypeLookup(actionNameToTypes);

        ActionNameSuggestions = BuildActionNameOptionSet(_entry.ActionBindings, _actionNameSuggestions);
        FilterVariableSuggestions = _filterVariableSuggestions;
        OnMissingActionOptions = NormalizeTargetOptionSet(DefaultOnMissingAction, onMissingActionOptions, _entry.ActionBindings.Select(static binding => binding.Target?.OnMissingAction));

        EventKeyComboBox.ItemsSource = EventKeyOptions;
        LaneComboBox.ItemsSource = LaneOptionValues;
        DispatchComboBox.ItemsSource = DispatchOptions;
        SourceMatchModeComboBox.ItemsSource = SourceMatchModeOptions;
        SecondarySourceMatchModeComboBox.ItemsSource = SourceMatchModeOptions;
        DispatchComboBox.SelectedItem = _entry.DispatchDisposition;
        SourceMatchModeComboBox.SelectedItem = _entry.SubscriptionSourceMatchMode;
        SecondarySourceMatchModeComboBox.SelectedItem = _entry.SubscriptionSecondarySourceMatchMode;
        if (!string.IsNullOrWhiteSpace(initialEventKey))
        {
            EventKeyComboBox.SelectedItem = EventKeyOptions.FirstOrDefault(option =>
                string.Equals(option, initialEventKey, StringComparison.OrdinalIgnoreCase));
        }
        else
        {
            EventKeyComboBox.SelectedItem = null;
        }
        var initialSubscriptionName = _entry.SubscriptionName?.Trim() ?? string.Empty;
        SubscriptionNameTextBox.Text = initialSubscriptionName;
        if (!string.IsNullOrWhiteSpace(initialSubscriptionName)
            && string.Equals(initialSubscriptionName, EventKeyComboBox.Text?.Trim(), StringComparison.OrdinalIgnoreCase))
        {
            _isAutoGeneratedSubscriptionName = true;
            _lastAutoGeneratedSubscriptionName = initialSubscriptionName;
        }
        var resolvedLane = NormalizeLane(_entry.Lane);
        LaneComboBox.SelectedItem = resolvedLane;
        IsEnabledCheckBox.IsChecked = _entry.IsEnabled;
        VisibleWhenContainedCheckBox.IsChecked = _entry.SubscriptionVisibleWhenContained;
        SourceScopeIdTextBox.Text = _entry.SubscriptionSourceScopeNodeId?.ToString("D") ?? string.Empty;
        SecondarySourceScopeIdTextBox.Text = _entry.SubscriptionSecondarySourceScopeNodeId?.ToString("D") ?? string.Empty;
        UpdateSourceScopeFieldsEnabledState();

        foreach (var binding in _entry.ActionBindings)
        {
            binding.Condition ??= new EventBindingConditionDefinition();
            binding.Target ??= new EventBindingTargetDefinition();
            binding.Condition.Filters ??= new List<EventBindingFilterConditionDefinition>();
            binding.InputArgumentMappings ??= new List<EventInputArgumentMappingDefinition>();

            if (binding.InputArgumentMappings.Count == 0 && _entry.InputArgumentMappings.Count > 0)
            {
                binding.InputArgumentMappings = CloneInputArgumentMappings(_entry.InputArgumentMappings);
            }
        }

        BindingsDataGrid.ItemsSource = _entry.ActionBindings;
        if (_entry.ActionBindings.Count > 0)
        {
            BindingsDataGrid.SelectedIndex = 0;
        }

        RefreshFilterGrid();
        _isInitializing = false;
    }

