    private void ChooseScopeIdIntoTextBox(
        System.Windows.Controls.TextBox targetTextBox,
        string title,
        SubscriptionSourceMatchMode? selectedMode)
    {
        if (_sourceScopeChoices.Count == 0)
        {
            WpfMessageBox.Show(
                this,
                "No scope choices are available for this context.",
                "Event Subscription",
                WpfMessageBoxButton.OK,
                WpfMessageBoxImage.Information);
            return;
        }

        var selectedKey = targetTextBox.Text?.Trim();
        if (string.IsNullOrWhiteSpace(selectedKey)
            || !Guid.TryParse(selectedKey, out var parsed)
            || parsed == Guid.Empty)
        {
            selectedKey = null;
        }
        else
        {
            selectedKey = parsed.ToString("D");
        }

        var dialog = new ScopeObjectChooserDialog(_sourceScopeChoices, title, expectedScope: null, selectedKey)
        {
            Owner = this
        };

        if (dialog.ShowDialog() != true || string.IsNullOrWhiteSpace(dialog.SelectedKey))
        {
            return;
        }

        targetTextBox.Text = dialog.SelectedKey.Trim();

        if (selectedMode is SubscriptionSourceMatchMode mode
            && mode != SubscriptionSourceMatchMode.ExplicitSourceId)
        {
            WpfMessageBox.Show(
                this,
                "Source Match is not set to ExplicitSourceId. The selected id will only apply when match mode is ExplicitSourceId.",
                "Event Subscription",
                WpfMessageBoxButton.OK,
                WpfMessageBoxImage.Information);
        }
    }

    private void UpdateSourceScopeFieldsEnabledState()
    {
        var sourceMatchMode = SourceMatchModeComboBox.SelectedItem is SubscriptionSourceMatchMode selectedMode
            ? selectedMode
            : SubscriptionSourceMatchMode.AnySource;
        var isPrimaryExplicit = sourceMatchMode == SubscriptionSourceMatchMode.ExplicitSourceId;
        SourceScopeIdTextBox.IsEnabled = isPrimaryExplicit;
        ChooseSourceScopeButton.IsEnabled = isPrimaryExplicit;
        ClearSourceScopeButton.IsEnabled = isPrimaryExplicit;

        var secondarySourceMatchMode = SecondarySourceMatchModeComboBox.SelectedItem is SubscriptionSourceMatchMode selectedSecondaryMode
            ? selectedSecondaryMode
            : SubscriptionSourceMatchMode.AnySource;
        var isSecondaryExplicit = secondarySourceMatchMode == SubscriptionSourceMatchMode.ExplicitSourceId;
        SecondarySourceScopeIdTextBox.IsEnabled = isSecondaryExplicit;
        ChooseSecondarySourceScopeButton.IsEnabled = isSecondaryExplicit;
        ClearSecondarySourceScopeButton.IsEnabled = isSecondaryExplicit;
    }

    private EventActionBindingDefinition? GetSelectedBinding()
    {
        if (BindingsDataGrid.SelectedItem is EventActionBindingDefinition selected)
        {
            return selected;
        }

        var fallback = _entry.ActionBindings.FirstOrDefault();
        if (fallback is not null)
        {
            BindingsDataGrid.SelectedItem = fallback;
        }

        return fallback;
    }

    private void RefreshFilterGrid()
    {
        var selectedBinding = GetSelectedBinding();
        if (selectedBinding is null)
        {
            FiltersDataGrid.ItemsSource = null;
            return;
        }

        selectedBinding.Condition ??= new EventBindingConditionDefinition();
        selectedBinding.Condition.Filters ??= new List<EventBindingFilterConditionDefinition>();
        // Filters are backed by List<T>; force a hard rebind so consecutive adds always render.
        FiltersDataGrid.ItemsSource = null;
        FiltersDataGrid.ItemsSource = selectedBinding.Condition.Filters;

        if (selectedBinding.Condition.Filters.Count > 0)
        {
            FiltersDataGrid.SelectedIndex = 0;
        }
    }

    private static List<string> ValidateEntry(EventSubscriptionDefinition entry)
    {
        var errors = new List<string>();
        if (string.IsNullOrWhiteSpace(entry.EventKey))
        {
            errors.Add("Event Key is required.");
        }

        var bindings = entry.ActionBindings ?? new List<EventActionBindingDefinition>();
        var duplicateOrders = bindings
            .GroupBy(static binding => binding.Order)
            .Where(static group => group.Count() > 1)
            .Select(static group => group.Key)
            .OrderBy(static order => order)
            .ToList();

        foreach (var duplicateOrder in duplicateOrders)
        {
            errors.Add($"Duplicate binding order '{duplicateOrder}'.");
        }

        for (var bindingIndex = 0; bindingIndex < bindings.Count; bindingIndex++)
        {
            var binding = bindings[bindingIndex];
            if (string.IsNullOrWhiteSpace(binding.Target?.ActionName))
            {
                errors.Add($"Binding {bindingIndex + 1}: Action Name is required.");
            }

            var filters = binding.Condition?.Filters ?? new List<EventBindingFilterConditionDefinition>();
            for (var filterIndex = 0; filterIndex < filters.Count; filterIndex++)
            {
                if (!string.IsNullOrWhiteSpace(filters[filterIndex].VariableName))
                {
                    continue;
                }

                errors.Add($"Binding {bindingIndex + 1}, Filter {filterIndex + 1}: Variable Name is required.");
            }
        }

        return errors;
    }

    private static EventSubscriptionDefinition CloneEntry(EventSubscriptionDefinition source)
    {
        var legacyMappings = CloneInputArgumentMappings(source.InputArgumentMappings ?? new List<EventInputArgumentMappingDefinition>());
        return new EventSubscriptionDefinition
        {
            Id = source.Id,
            EventKey = source.EventKey,
            SubscriptionName = ResolveSubscriptionDisplayName(source),
            IsEnabled = source.IsEnabled,
            Lane = source.Lane,
            DispatchDisposition = source.DispatchDisposition,
            SubscriptionVisibleWhenContained = source.SubscriptionVisibleWhenContained,
            SubscriptionSourceMatchMode = source.SubscriptionSourceMatchMode,
            SubscriptionSourceScopeNodeId = source.SubscriptionSourceScopeNodeId,
            SubscriptionSecondarySourceMatchMode = source.SubscriptionSecondarySourceMatchMode,
            SubscriptionSecondarySourceScopeNodeId = source.SubscriptionSecondarySourceScopeNodeId,
            InputArgumentMappings = legacyMappings,
            ActionBindings = (source.ActionBindings ?? new List<EventActionBindingDefinition>())
                .Select(binding =>
                {
                    var bindingMappings = CloneInputArgumentMappings(binding.InputArgumentMappings ?? new List<EventInputArgumentMappingDefinition>());
                    if (bindingMappings.Count == 0 && legacyMappings.Count > 0)
                    {
                        bindingMappings = CloneInputArgumentMappings(legacyMappings);
                    }

                    return new EventActionBindingDefinition
                    {
                        Order = binding.Order,
                        IsEnabled = binding.IsEnabled,
                        Target = new EventBindingTargetDefinition
                        {
                            ActionName = binding.Target?.ActionName ?? string.Empty,
                            OnMissingAction = binding.Target?.OnMissingAction ?? DefaultOnMissingAction,
                            StopChainOnFailure = binding.Target?.StopChainOnFailure ?? true
                        },
                        Condition = new EventBindingConditionDefinition
                        {
                            QuantityEvaluationMode = binding.Condition?.QuantityEvaluationMode
                                ?? RuntimeVariableQuantityEvaluationMode.AllResolvedMustPass,
                            Filters = (binding.Condition?.Filters ?? new List<EventBindingFilterConditionDefinition>())
                                .Select(static filter => new EventBindingFilterConditionDefinition
                                {
                                    VariableName = filter.VariableName,
                                    Operator = filter.Operator,
                                    ExpectedValue = filter.ExpectedValue
                                })
                                .ToList()
                        },
                        InputArgumentMappings = bindingMappings
                    };
                })
                .ToList()
        };
    }

    private static List<EventInputArgumentMappingDefinition> CloneInputArgumentMappings(
        IReadOnlyList<EventInputArgumentMappingDefinition> source)
    {
        return source
            .Select(static mapping => mapping.CloneNormalized())
            .Where(static mapping =>
                mapping.SourceType == EventInputArgumentMappingSourceType.ConstantValue
                    ? !string.IsNullOrWhiteSpace(mapping.OutputActionPayloadArgKey)
                    : !string.IsNullOrWhiteSpace(mapping.InputEventPaylloadArgKey))
            .ToList();
    }

    private static string ResolveSubscriptionDisplayName(EventSubscriptionDefinition entry)
    {
        return ResolveSubscriptionDisplayName(entry.SubscriptionName, entry.EventKey);
    }

    private static string ResolveSubscriptionDisplayName(string? subscriptionName, string? eventKey)
    {
        var normalizedName = subscriptionName?.Trim() ?? string.Empty;
        if (!string.IsNullOrWhiteSpace(normalizedName))
        {
            return normalizedName;
        }

        return eventKey?.Trim() ?? string.Empty;
    }

    private static IReadOnlyList<string> NormalizeSuggestions(IReadOnlyList<string>? source)
    {
        return (source ?? Array.Empty<string>())
            .Select(static item => item?.Trim() ?? string.Empty)
            .Where(static item => !string.IsNullOrWhiteSpace(item))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(static item => item, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private static IReadOnlyList<ScopeObjectChoiceItem> NormalizeSourceScopeChoices(
        IReadOnlyList<ScopeObjectChoiceItem>? source)
    {
        return (source ?? Array.Empty<ScopeObjectChoiceItem>())
            .Where(static item =>
                !string.IsNullOrWhiteSpace(item.Key)
                && Guid.TryParse(item.Key.Trim(), out var parsed)
                && parsed != Guid.Empty)
            .GroupBy(static item => item.Key.Trim(), StringComparer.OrdinalIgnoreCase)
            .Select(static group => group.First())
            .OrderBy(static item => item.DisplayName, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private static IReadOnlyDictionary<string, IReadOnlyList<CommandActionType>> NormalizeActionTypeLookup(
        IReadOnlyDictionary<string, IReadOnlyList<CommandActionType>>? source)
    {
        var lookup = new Dictionary<string, IReadOnlyList<CommandActionType>>(StringComparer.OrdinalIgnoreCase);
        if (source is null)
        {
            return lookup;
        }

        foreach (var pair in source)
        {
            var actionName = pair.Key?.Trim() ?? string.Empty;
            if (string.IsNullOrWhiteSpace(actionName))
            {
                continue;
            }

            lookup[actionName] = (pair.Value ?? Array.Empty<CommandActionType>())
                .Distinct()
                .OrderBy(static actionType => actionType.ToString(), StringComparer.OrdinalIgnoreCase)
                .ToList();
        }

        return lookup;
    }

    private static string ReadTrimmedString(JsonElement element, string propertyName)
    {
        if (!element.TryGetProperty(propertyName, out var value)
            || value.ValueKind != JsonValueKind.String)
        {
            return string.Empty;
        }

        return value.GetString()?.Trim() ?? string.Empty;
    }

    private static IReadOnlyList<string> NormalizeTargetOptionSet(
        string defaultValue,
        IReadOnlyList<string>? preferredValues,
        IEnumerable<string?> authoredValues)
    {
        var values = new List<string> { defaultValue };
        values.AddRange(preferredValues ?? Array.Empty<string>());
        values.AddRange(authoredValues.Where(static value => !string.IsNullOrWhiteSpace(value))!);

        return values
            .Select(static value => value?.Trim() ?? string.Empty)
            .Where(static value => !string.IsNullOrWhiteSpace(value))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(static value => value, StringComparer.OrdinalIgnoreCase)
            .OrderBy(value => string.Equals(value, defaultValue, StringComparison.OrdinalIgnoreCase) ? 0 : 1)
            .ToList();
    }

    private static IReadOnlyList<string> BuildActionNameOptionSet(
        IEnumerable<EventActionBindingDefinition> bindings,
        IReadOnlyList<string> preferredValues)
    {
        var values = new List<string>();
        values.AddRange(preferredValues);
        values.AddRange(bindings
            .Select(static binding => binding.Target?.ActionName)
            .Where(static value => !string.IsNullOrWhiteSpace(value))
            .Select(static value => value!));
        values.Add("inspect");

        return values
            .Select(static value => value?.Trim() ?? string.Empty)
            .Where(static value => !string.IsNullOrWhiteSpace(value))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(static value => value, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private static string NormalizeLane(string? lane)
    {
        var normalized = lane?.Trim() ?? string.Empty;
        if (LaneOptions.Value.Any(option => string.Equals(option, normalized, StringComparison.OrdinalIgnoreCase)))
        {
            return LaneOptions.Value.First(option => string.Equals(option, normalized, StringComparison.OrdinalIgnoreCase));
        }

        return DefaultLane;
    }

    private static IReadOnlyList<string> LoadLaneOptionsFromSchema()
    {
        var fallback = new List<string> { "foreground", "background" };
        var schemaPath = Path.Combine(AppContext.BaseDirectory, EventSubscriptionSchemaRelativePath);
        if (!File.Exists(schemaPath))
        {
            return fallback;
        }

        try
        {
            using var stream = File.OpenRead(schemaPath);
            using var document = JsonDocument.Parse(stream);

            if (!document.RootElement.TryGetProperty("properties", out var properties)
                || properties.ValueKind != JsonValueKind.Object
                || !properties.TryGetProperty("lane", out var lane)
                || lane.ValueKind != JsonValueKind.Object
                || !lane.TryGetProperty("enum", out var enumValues)
                || enumValues.ValueKind != JsonValueKind.Array)
            {
                return fallback;
            }

            var values = enumValues
                .EnumerateArray()
                .Where(static element => element.ValueKind == JsonValueKind.String)
                .Select(static element => element.GetString()?.Trim() ?? string.Empty)
                .Where(static value => !string.IsNullOrWhiteSpace(value))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();

            return values.Count > 0 ? values : fallback;
        }
        catch
        {
            return fallback;
        }
    }
