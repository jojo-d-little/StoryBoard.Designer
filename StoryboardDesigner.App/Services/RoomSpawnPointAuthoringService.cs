using StoryboardDesigner.App.Models;

namespace StoryboardDesigner.App.Services;

/// <summary>Creates missing traversal arrival points while leaving existing authored points intact.</summary>
public static class RoomSpawnPointAuthoringService
{
    public static void EnsureAreaSpawnPoints(Area area)
    {
        ArgumentNullException.ThrowIfNull(area);
        foreach (var room in area.Rooms)
        {
            var points = room.SpawnPoints.ToList();

            for (var index = 0; index < points.Count; index++)
            {
                var point = points[index];
                if (!point.IsAutoGeneratedPosition) continue;
                if (point.GeneratedPositionX != point.X || point.GeneratedPositionY != point.Y)
                {
                    points[index] = point with { IsAutoGeneratedPosition = false, GeneratedPositionX = null, GeneratedPositionY = null };
                    continue;
                }

                var traversal = point.TraversalConnectionId is Guid traversalId
                    ? area.TraversalConnections.FirstOrDefault(connection => connection.TraversalConnectionId == traversalId)
                    : null;
                if (point.TraversalConnectionId.HasValue
                    && (traversal is null || !PermitsEntry(traversal, room.Id)))
                    continue;
                var x = traversal is null ? room.RoomImageCanvasWidth / 2d : GetInitialX(room, ArrivalDirection(traversal, room.Id));
                var y = traversal is null ? room.RoomImageCanvasHeight / 2d : GetInitialY(room, ArrivalDirection(traversal, room.Id));
                points[index] = point with { X = x, Y = y, GeneratedPositionX = x, GeneratedPositionY = y };
            }

            foreach (var traversal in area.TraversalConnections)
            {
                if (!PermitsEntry(traversal, room.Id) || points.Any(point => point.TraversalConnectionId == traversal.TraversalConnectionId))
                    continue;

                var arrivalDirection = ArrivalDirection(traversal, room.Id);
                points.Add(new RoomSpawnPoint(
                    GetInitialX(room, arrivalDirection),
                    GetInitialY(room, arrivalDirection),
                    GetTopRenderOrder(room),
                    IsDefault: false,
                    TraversalConnectionId: traversal.TraversalConnectionId)
                {
                    IsAutoGeneratedPosition = true,
                    GeneratedPositionX = GetInitialX(room, arrivalDirection),
                    GeneratedPositionY = GetInitialY(room, arrivalDirection)
                });
            }

            if (!points.SequenceEqual(room.SpawnPoints))
                room.SpawnPoints = points;
        }
    }

    public static bool PermitsEntry(TraversalConnection connection, Guid roomId) =>
        roomId == connection.RoomBId && connection.TraversalAccessMode is TraversalAccessMode.TwoWay or TraversalAccessMode.OneWayAtoB
        || roomId == connection.RoomAId && connection.TraversalAccessMode is TraversalAccessMode.TwoWay or TraversalAccessMode.OneWayBtoA;

    public static Direction10 ArrivalDirection(TraversalConnection connection, Guid destinationRoomId)
    {
        var fromA = destinationRoomId == connection.RoomBId;
        return fromA ? connection.BaseTraversalDirectionFromA : Invert(connection.BaseTraversalDirectionFromA);
    }

    /// <summary>Direction from this room toward the other room, for room-relative labels.</summary>
    public static Direction10 DirectionFromRoom(TraversalConnection connection, Guid roomId) =>
        roomId == connection.RoomAId
            ? connection.BaseTraversalDirectionFromA
            : Invert(connection.BaseTraversalDirectionFromA);

    private static int GetTopRenderOrder(Room room)
    {
        var maximum = 1000 + room.GameObjects.Count;
        void Visit(IReadOnlyList<GameObject> objects)
        {
            for (var index = 0; index < objects.Count; index++)
            {
                var current = objects[index];
                maximum = Math.Max(maximum, current.RenderZOrder != 0 ? current.RenderZOrder : 1000 + objects.Count - index);
                Visit(current.ContainedObjects);
            }
        }
        Visit(room.GameObjects);
        return maximum + 1;
    }

    private static double GetInitialX(Room room, Direction10 arrival) => arrival switch
    {
        Direction10.East or Direction10.NorthEast or Direction10.SouthEast => 36,
        Direction10.West or Direction10.NorthWest or Direction10.SouthWest => Math.Max(0, room.RoomImageCanvasWidth - 36),
        _ => room.RoomImageCanvasWidth / 2d
    };

    private static double GetInitialY(Room room, Direction10 arrival) => arrival switch
    {
        Direction10.South or Direction10.SouthEast or Direction10.SouthWest => 36,
        Direction10.North or Direction10.NorthEast or Direction10.NorthWest => Math.Max(0, room.RoomImageCanvasHeight - 36),
        _ => room.RoomImageCanvasHeight / 2d
    };

    private static Direction10 Invert(Direction10 direction) => direction switch
    {
        Direction10.North => Direction10.South,
        Direction10.NorthEast => Direction10.SouthWest,
        Direction10.East => Direction10.West,
        Direction10.SouthEast => Direction10.NorthWest,
        Direction10.South => Direction10.North,
        Direction10.SouthWest => Direction10.NorthEast,
        Direction10.West => Direction10.East,
        Direction10.NorthWest => Direction10.SouthEast,
        Direction10.Up => Direction10.Down,
        Direction10.Down => Direction10.Up,
        _ => direction
    };
}
