namespace StoryboardDesigner.App.Models;

/// <summary>A room-space player arrival point, optionally associated with an incoming traversal.</summary>
public sealed record RoomSpawnPoint(
    double X,
    double Y,
    int? RenderZOrder = null,
    bool IsDefault = false,
    Guid? TraversalConnectionId = null,
    Direction10? FacingOverride = null)
{
    // Designer-only state persisted in a separate authoring metadata sidecar.
    public bool IsAutoGeneratedPosition { get; init; }
    public double? GeneratedPositionX { get; init; }
    public double? GeneratedPositionY { get; init; }
}
